'use strict';

const fs = require('node:fs');
const path = require('node:path');
const directory = path.join(__dirname, '..', 'assets', 'audio');
const output = path.join(directory, 'manifest.js');
const preference = ['.mp3', '.ogg', '.wav'];
const files = fs.readdirSync(directory, {withFileTypes: true})
  .filter(entry => entry.isFile()).map(entry => entry.name).sort();
const entries = Object.create(null);
for (const extension of preference) {
  for (const file of files) {
    if (path.extname(file).toLowerCase() !== extension) continue;
    const key = path.basename(file, path.extname(file)).toLowerCase();
    entries[key] ??= 'assets/audio/' + encodeURIComponent(file);
  }
}
const manifest = '// Generated by node _tools/sync-audio.cjs.\nwindow.Sky ||= {};\n' +
  'window.Sky.audioManifest = ' + JSON.stringify(entries, null, 2) + ';\n';
if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== manifest) fs.writeFileSync(output, manifest);
console.log('manifest.js: ' + Object.keys(entries).join(', '));
