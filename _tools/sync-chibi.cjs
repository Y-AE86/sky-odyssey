'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
require('../js/data.js');

const root = path.join(__dirname, '..');
const { D } = globalThis.Sky;
const browser = vm.createContext({window:{Sky:{D}}});
vm.runInContext(fs.readFileSync(path.join(root, 'js/assets.js'), 'utf8'), browser);
const art = browser.window.Sky.art;
const chibiDir = path.join(root, 'assets', 'chibi');
const poses = fs.readdirSync(chibiDir,{withFileTypes:true}).filter(file=>file.isFile())
  .map(file=>/^chibi_(h\d{2}_(?:windup|atk|hurt))\.png$/.exec(file.name)?.[1])
  .filter(Boolean).sort();
browser.window.Sky.chibiPoses = poses;
const files = [
  ...[...D.heroes, ...D.enemies].map(({id})=>[id,art(id,'chibi')]),
  ...poses.map(key=>[key,art.pose(...key.split('_'))])
];
const signature = Buffer.from([137,80,78,71,13,10,26,10]);
const images = Object.fromEntries(files.map(([key,file]) => {
  const png = fs.readFileSync(path.join(root,file));
  if (png.length<24 || !png.subarray(0, 8).equals(signature) ||
      png.readUInt32BE(16) < 2 || png.readUInt32BE(20) < 2) {
    throw new Error('Expected an original combat PNG for '+key);
  }
  return [key, 'data:image/png;base64,' + png.toString('base64')];
}));
function writeGenerated(file,property,value,indent) {
  const target=path.join(root,'js',file);
  const contents='// Generated by node _tools/sync-chibi.cjs.\nwindow.Sky.'+property+' = '+
    JSON.stringify(value,null,indent)+';\n';
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8')!==contents) fs.writeFileSync(target,contents);
}
writeGenerated('offline-textures.js','offlineChibi',images,2);
writeGenerated('chibi-poses.js','chibiPoses',poses);
console.log('Packed '+Object.keys(images).length+' original PNGs, including '+poses.length+' action poses');
