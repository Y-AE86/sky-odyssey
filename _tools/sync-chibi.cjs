'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
require('../js/data.js');

const root = path.join(__dirname, '..');
const { D } = globalThis.Sky;
const browser = vm.createContext({window:{Sky:{D}}});
vm.runInContext(fs.readFileSync(path.join(root, 'js/assets.js'), 'utf8'), browser);
const art = browser.window.Sky.art;
const images = Object.fromEntries([...D.heroes, ...D.enemies].map(({id}) => {
  const png = fs.readFileSync(path.join(root, art(id, 'chibi')));
  if (!png.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10])) ||
      png.readUInt32BE(16) < 2 || png.readUInt32BE(20) < 2) {
    throw new Error('Expected an original combat PNG for '+id);
  }
  return [id, 'data:image/png;base64,' + png.toString('base64')];
}));
const target = path.join(root, 'js/offline-textures.js');
const pack = '// Generated by node _tools/sync-chibi.cjs.\nwindow.Sky.offlineChibi = ' +
  JSON.stringify(images, null, 2) + ';\n';
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== pack) fs.writeFileSync(target, pack);
console.log('Packed '+Object.keys(images).length+' original PNGs');
