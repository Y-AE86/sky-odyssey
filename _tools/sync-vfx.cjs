'use strict';

const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname,'..');
const directory = path.join(root,'assets','vfx');
const entries = {};
const fieldArt = {};
const files = fs.readdirSync(directory,{withFileTypes:true})
  .filter(file => file.isFile()).map(file => file.name).sort();
for(const name of files) {
  const id = name==='vfx_hit_spark.png' ? 'spark' : /^vfx_ult_(h0[1-6])\.png$/.exec(name)?.[1];
  const single = /^(proj_h0[1-6]|status_(?:shield|freeze|curse|heal_ring)|vfx_impact_crack)\.png$/.exec(name)?.[1];
  if(!id && !single) continue;
  const png = fs.readFileSync(path.join(directory,name));
  (id ? entries : fieldArt)[id || single] = 'data:image/png;base64,'+png.toString('base64');
}
function writePack(filename,property,images){
  const target = path.join(root,'js',filename);
  const script = '// Generated by node _tools/sync-vfx.cjs.\nwindow.Sky.'+property+' = '+JSON.stringify(images,null,2)+';\n';
  if(!fs.existsSync(target) || fs.readFileSync(target,'utf8')!==script) fs.writeFileSync(target,script);
  console.log(filename+' ('+Object.keys(images).length+'): '+Object.keys(images).join(', '));
}
writePack('offline-vfx.js','offlineVfx',entries);
writePack('offline-battle-art.js','offlineBattleArt',fieldArt);
