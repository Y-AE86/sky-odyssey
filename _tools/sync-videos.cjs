'use strict';

const fs = require('node:fs');
const path = require('node:path');
const directory = path.join(__dirname, '..', 'assets', 'videos');
const entries = {lobby_cg:[],ult:[]};
for (const file of fs.readdirSync(directory,{withFileTypes:true})) {
  const match=/^(lobby_cg|ult)_(h\d{2})\.mp4$/.exec(file.name);
  if (!match || !file.isFile() || !fs.statSync(path.join(directory,file.name),{throwIfNoEntry:false})?.size) continue;
  const [,kind,id]=match;
  entries[kind].push(id);
}
const posterIds=entries.lobby_cg.sort();
const ultimateIds=entries.ult.sort();
const manifest = '// Generated by node _tools/sync-videos.cjs.\n' +
  'window.Sky.posterVideoIds = '+JSON.stringify(posterIds)+';\n' +
  'window.Sky.ultVideoIds = '+JSON.stringify(ultimateIds)+';\n';
const target = path.join(directory,'manifest.js');
if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== manifest) {
  fs.writeFileSync(target,manifest);
}
console.log('Enabled poster videos: '+(posterIds.join(', ') || 'none'));
console.log('Enabled ultimate videos: '+(ultimateIds.join(', ') || 'none'));
